"""Experiment 2 -- what is lost by dropping the delay.

The delay enters neither the equilibria nor the reproduction number
R0 = beta*S*/(gamma+mu_I), so every run in parts (a) and (b) has
*exactly* the same R0 and the same endemic state.  Whatever differs is therefore
a consequence of the delay alone, which makes this a clean experiment rather
than a restatement of "different parameters give different curves".

Part (a) integrates one parameter set at several delays.  Part (b) is the part
that matters in practice: a delay-free SIR is *calibrated* to early data
generated by the delay model -- the situation of an analyst three weeks into an
outbreak -- and then used to forecast.  The early fit is excellent and the
forecast is badly wrong, because the two models need different beta to produce
the same observed growth rate,

    r + gamma + mu_I = beta * S* * exp(-r*tau),

so matching r at tau = 0 requires a transmission rate smaller by exp(r*tau).

Part (c) connects back to Theorem 2: at the realistic super-critical parameter
sets of Table 1 the delay can destroy positivity outright, and does so in a way
that is independent of the step size and hence a property of the continuous
model rather than of the discretisation.

The Ebola set of Table 1 is used for (a) and (b) because its solutions stay
non-negative for every delay considered, so the comparison is between valid
trajectories throughout.  The COVID-19 set, which does lose positivity, is the
subject of (c).
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from scipy.optimize import least_squares

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sirdelay import COVID, EBOLA, solve                            # noqa: E402
from sirdelay.analysis import growth_rate, peak_metrics             # noqa: E402
from sirdelay.export import banner, write_macros, write_table       # noqa: E402
from sirdelay.fitting import fit_growth_rate                        # noqa: E402

PAR = EBOLA
I_SEED = 1e-6
T_END = 800.0
H = 0.05
TAUS = (0.0, 1.0, 5.0, 10.0, 20.0, 30.0)


def run(par=PAR, *, tau, beta=None, I0=I_SEED, T=T_END, h=H, record="full"):
    return solve(Lambda=par.Lambda, beta=par.beta if beta is None else beta,
                 gamma=par.gamma, mu_S=par.mu_S, mu_I=par.mu_I, mu_R=par.mu_R,
                 tau=tau, S0=1.0 - I0, I0=I0, R0=0.0, T=T, h=h, record=record)


def measured_growth(sol, *, lo=1e-5, hi=1e-3) -> float:
    """Growth rate over the *first* passage of I through the exponential phase.

    Masking on ``lo < I < hi`` alone would also pick up the decaying side of the
    epidemic and average the two slopes to roughly zero.
    """
    I = np.asarray(sol.I)
    i0 = int(np.argmax(I > lo))
    i1 = int(np.argmax(I > hi))
    if i1 <= i0:
        i1 = len(I)
    return fit_growth_rate(sol.t[i0:i1], I[i0:i1]).r


# ---------------------------------------------------------------------------
def part_a() -> dict:
    banner("2a  same R0, same equilibria, different delay")
    print(f"  Ebola set of Table 1: beta = {PAR.beta}, gamma = {PAR.gamma}, "
          f"mu_I = {PAR.mu_I:g}")
    print(f"  R0 = beta*S*/(gamma+mu_I) = {PAR.R0:.4f}  (independent of tau)\n")
    print(f"    {'tau':>5}  {'r fitted':>9}  {'r theory':>9}  {'t_peak':>8}  "
          f"{'I_peak':>9}  {'attack':>8}  {'pos':>5}")
    rows, cols = [], {}
    for tau in TAUS:
        sol = run(tau=tau)
        m = peak_metrics(sol)
        r_num = measured_growth(sol)
        r_th = growth_rate(beta=PAR.beta, gamma=PAR.gamma, mu_I=PAR.mu_I,
                           S_star=PAR.S_star, tau=tau)
        rows.append((tau, r_num, r_th, m["t_peak"], m["I_peak"],
                     m["cumulative_incidence"], bool(sol.positive)))
        print(f"    {tau:5g}  {r_num:9.4f}  {r_th:9.4f}  {m['t_peak']:8.1f}  "
              f"{m['I_peak']:9.4f}  {m['cumulative_incidence']:8.4f}  "
              f"{str(bool(sol.positive)):>5}")
        key = f"{tau:g}".replace(".", "p")
        step = max(1, len(sol.t) // 1200)
        cols.setdefault("t", sol.t[::step])
        cols[f"I{key}"] = np.asarray(sol.I)[::step]
        cols[f"S{key}"] = np.asarray(sol.S)[::step]
    assert all(r[6] for r in rows), "part (a) requires non-negative trajectories"
    rel = max(abs(r[1] / r[2] - 1.0) for r in rows)
    print(f"\n  fitted growth rates match the characteristic equation to "
          f"{100*rel:.1f}% or better")
    a, z = rows[0], rows[TAUS.index(30.0)]
    print(f"  going from tau = 0 to tau = 30 days at fixed R0 = {PAR.R0:.2f}:")
    print(f"    growth rate      {a[1]:.4f} -> {z[1]:.4f} /day  "
          f"({100*(z[1]/a[1]-1):+.0f}%)")
    print(f"    peak time        {a[3]:.0f} -> {z[3]:.0f} days  "
          f"({z[3]-a[3]:+.0f} days)")
    print(f"    peak prevalence  {a[4]:.4f} -> {z[4]:.4f}  "
          f"({100*(z[4]/a[4]-1):+.0f}%)")
    write_table("exp2a_delays", cols,
                comment=f"Experiment 2a -- Ebola parameter set of Table 1 at several\n"
                        f"delays.  R0 = {PAR.R0:.2f} in every column; only tau differs.")
    return {"rows": rows, "rate_match": rel}


# ---------------------------------------------------------------------------
def part_b(*, tau_true=10.0, fit_days=21.0) -> dict:
    """Calibrate a delay-free SIR to early delay-model data, then forecast."""
    banner("2b  calibration mismatch -- fitting a delay-free model to early data")
    truth = run(tau=tau_true)
    t, I_true = truth.t, np.asarray(truth.I)

    detect = float(t[np.argmax(I_true > 1e-5)])
    win = (t >= detect) & (t <= detect + fit_days)
    r_obs = fit_growth_rate(t[win], I_true[win]).r
    print(f"  truth: delay model, tau = {tau_true:g} d, beta = {PAR.beta}, "
          f"R0 = {PAR.R0:.3f}")
    print(f"  analyst sees days {detect:.0f}-{detect+fit_days:.0f} only; "
          f"observed growth rate r = {r_obs:.4f} /day")

    # Least-squares calibration of a delay-free SIR on that window, with both the
    # transmission rate and the (unknown) seeding level free.  Fitting the seed
    # as well is what makes the early agreement genuinely excellent, so that the
    # forecast error below cannot be blamed on a poor fit.
    def residual(x):
        beta, seed = np.exp(x)
        sol = run(tau=0.0, beta=beta, I0=seed, T=detect + fit_days + 1.0)
        I = np.interp(t[win], sol.t, np.asarray(sol.I))
        return np.log(np.maximum(I, 1e-300)) - np.log(I_true[win])

    fit = least_squares(residual, np.log([0.15, I_SEED]), xtol=1e-13, ftol=1e-13)
    beta_ode, seed_ode = np.exp(fit.x)
    R0_ode = beta_ode * PAR.S_star / (PAR.gamma + PAR.mu_I)
    err_fit = float(np.max(np.abs(fit.fun)))
    print(f"  best delay-free fit: beta = {beta_ode:.4f}, seed = {seed_ode:.3e}")
    print(f"  max log-error on the fitting window: {err_fit:.2e} "
          f"({100*(np.exp(err_fit)-1):.2f}% in I) -- the early fit is excellent")
    print(f"\n  R0 recovered by the delay-free fit : {R0_ode:.4f}")
    print(f"  true R0                            : {PAR.R0:.4f}")
    print(f"  ratio                              : {PAR.R0/R0_ode:.4f}")
    print(f"  predicted ratio exp(r*tau)         : {np.exp(r_obs*tau_true):.4f}")
    print(f"  -> the delay-free calibration under-estimates R0 by "
          f"{100*(1-R0_ode/PAR.R0):.0f}%")

    naive = run(tau=0.0, beta=beta_ode, I0=seed_ode)
    m_true, m_naive = peak_metrics(truth), peak_metrics(naive)
    I_naive = np.interp(t, naive.t, np.asarray(naive.I))
    print(f"\n    {'quantity':<22} {'delay model':>13} {'delay-free fit':>15} "
          f"{'error':>9}")
    out = {}
    for label, key in (("peak time [d]", "t_peak"),
                       ("peak prevalence", "I_peak"),
                       ("attack size", "cumulative_incidence")):
        a, b = m_true[key], m_naive[key]
        rel = 100.0 * (b - a) / a
        print(f"    {label:<22} {a:13.5f} {b:15.5f} {rel:8.0f}%")
        out[key] = (a, b, rel)

    step = max(1, len(t) // 1200)
    write_table("exp2b_mismatch",
                {"t": t[::step], "Itrue": I_true[::step], "Inaive": I_naive[::step]},
                comment=f"Experiment 2b -- truth is the delay model (tau = {tau_true:g});\n"
                        f"'naive' is a delay-free SIR least-squares calibrated to the\n"
                        f"same data over days {detect:.0f}-{detect+fit_days:.0f}.")
    return {"r_obs": r_obs, "beta_ode": beta_ode, "R0_ode": R0_ode,
            "R0_true": PAR.R0, "err_fit": err_fit, "tau": tau_true,
            "ratio": PAR.R0 / R0_ode, "predicted": float(np.exp(r_obs * tau_true)),
            "win_lo": detect, "win_hi": detect + fit_days, **out}


