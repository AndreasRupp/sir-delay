def part_c() -> dict:
    """Positivity at the realistic parameter sets, as a function of the delay."""
    banner("2c  the delay can destroy positivity at realistic parameters")
    print("  Both Table 1 sets violate the hypotheses of Theorem 2 by about two")
    print("  orders of magnitude, so nothing is guaranteed.  What actually happens")
    print("  depends on the delay, and it is not monotone.\n")
    taus = np.linspace(0.0, 40.0, 161)
    cols = {"tau": taus}
    res = {}
    for name, par in (("ebola", EBOLA), ("covid", COVID)):
        per_h = {}
        for h in (0.2, 0.05, 0.02):
            minS = np.array([
                float(run(par, tau=float(tt), T=600.0, h=h,
                          record="summary").min_S) for tt in taus])
            per_h[h] = minS
        cols[f"minS_{name}"] = per_h[0.02]
        cols[f"minS_{name}_coarse"] = per_h[0.2]
        neg = per_h[0.02] < 0.0
        if neg.any():
            lo, hi = taus[neg].min(), taus[neg].max()
            print(f"    {name:6s}: positivity lost for tau in "
                  f"[{lo:.2f}, {hi:.2f}] days")
            res[name] = (float(lo), float(hi))
        else:
            print(f"    {name:6s}: positivity preserved for every tau tested "
                  f"(0 to {taus[-1]:g} days)")
            res[name] = None
        # h-independence: the sign pattern must not depend on the discretisation
        agree = bool(np.all((per_h[0.2] < 0) == (per_h[0.02] < 0)))
        print(f"            classification identical for h = 0.2 and h = 0.02: "
              f"{agree}")
        res[f"{name}_h_agree"] = agree
    write_table("exp2c_positivity", cols,
                comment="Experiment 2c -- minimum of S over the run as a function of\n"
                        "the delay, for the two realistic parameter sets of Table 1.\n"
                        "Negative values mean positivity is lost.  The coarse column\n"
                        "(h = 0.2) is shown to confirm the effect is not a\n"
                        "discretisation artefact.")
    return res


def part_d() -> dict:
    """Sustained oscillations: behaviour the delay-free model cannot produce.

    Linearising at the endemic equilibrium S* = (gamma+mu_I)/beta,
    I* = (Lambda - mu_S S*)/(gamma+mu_I) and writing a := beta*I* =
    mu_S(R0-1), g := gamma+mu_I, the characteristic equation is

        z^2 + (g+mu_S) z + mu_S g + exp(-z tau)[(a-g) z + g(a-mu_S)] = 0.

    For tau = 0 the equation reduces to z^2 + (mu_S+a) z + g a = 0, whose roots
    have negative real part, so the delay-free model approaches the endemic
    state: the sustained oscillations below exist only because of the delay.

    The parameter set is the super-critical example of Section 3, which
    satisfies the hypotheses of Theorem 2 (Lambda*beta = 3.6 <= 4 mu^2 = 4), so
    positivity and the bound N(t) <= 1 hold throughout.
    """
    banner("2d  delay-induced sustained oscillations")
    par = EBOLA.with_(Lambda=1.0, beta=3.6, gamma=0.1,
                      mu_S=1.0, mu_I=1.0, mu_R=1.0, name="oscillatory")
    S0, I0, R0h = 0.4, 0.3, 0.3
    N0_bar = S0 + I0 + R0h
    print(f"  Lambda = 1, mu_S = mu_I = mu_R = 1, beta = {par.beta}, "
          f"gamma = {par.gamma}")
    print(f"  R0 = {par.R0:.4f} (super-critical, and > 3)")
    print(f"  balance condition  Lambda*beta = {par.beta:.2f} <= 4 mu^2 = "
          f"{4*par.mu**2:.2f} : {par.beta <= 4*par.mu**2}")
    print(f"  history  N0_bar = {N0_bar:.2f} < 2 sqrt(Lambda/beta) = "
          f"{2*np.sqrt(1.0/par.beta):.4f} : {N0_bar < 2*np.sqrt(1.0/par.beta)}\n")
    print(f"    {'tau':>6}  {'amplitude of I':>15}  {'min S':>10}  {'max N':>10}")
    cols = {}
    T = 400.0
    for tau in (0.0, 3.0, 4.0):
        sol = solve(Lambda=par.Lambda, beta=par.beta, gamma=par.gamma,
                    mu_S=par.mu_S, mu_I=par.mu_I, mu_R=par.mu_R, tau=tau,
                    S0=S0, I0=I0, R0=R0h, T=T, h=0.005)
        I = np.asarray(sol.I)
        tail = I[int(340 / sol.h):]
        amp = float(tail.max() - tail.min())
        print(f"    {tau:6g}  {amp:15.5f}  {float(sol.min_S):10.5f}  "
              f"{float(sol.max_N):10.6f}")
        key = f"{tau:g}".replace(".", "p")
        step = max(1, len(sol.t) // 1500)
        cols.setdefault("t", sol.t[::step])
        cols[f"I{key}"] = I[::step]
    print(f"\n  positivity and the bound N(t) <= max(N0_bar, Lambda/mu) hold "
          f"throughout")
    write_table("exp2d_hopf", cols,
                comment="Experiment 2d -- delay-induced oscillations at Lambda=1,\n"
                        "mu=1, beta=3.6, gamma=0.1, history (0.4,0.3,0.3).  The\n"
                        "tau = 0 column approaches the endemic state monotonically.")


# ---------------------------------------------------------------------------
def main() -> None:
    a = part_a()
    b = part_b()
    c = part_c()
    part_d()

    tau0, tau30 = a["rows"][0], a["rows"][TAUS.index(30.0)]
    cov = c["covid"]
    write_macros("exp2_macros", {
        "expTwoRZero": f"{PAR.R0:.2f}",
        "expTwoRateZero": f"{tau0[1]:.3f}",
        "expTwoRateThirty": f"{tau30[1]:.3f}",
        "expTwoPeakShift": f"{tau30[3]-tau0[3]:.0f}",
        "expTwoPeakDrop": f"{100*(1-tau30[4]/tau0[4]):.0f}",
        "expTwoFitRZero": f"{b['R0_ode']:.2f}",
        "expTwoFitRZeroBias": f"{100*(1-b['R0_ode']/b['R0_true']):.0f}",
        "expTwoFitLogErr": f"{100*(np.exp(b['err_fit'])-1):.2f}",
        "expTwoPeakPrevErr": f"{b['I_peak'][2]:.0f}",
        "expTwoAttackErr": f"{b['cumulative_incidence'][2]:.0f}",
        "expTwoCovidTauLo": f"{cov[0]:.1f}" if cov else "n/a",
        "expTwoWinLo": f"{b['win_lo']:.0f}",
        "expTwoWinHi": f"{b['win_hi']:.0f}",
    }, comment="Experiment 2 -- consequences of neglecting the delay.")
    banner("experiment 2 complete")


if __name__ == "__main__":
    main()
